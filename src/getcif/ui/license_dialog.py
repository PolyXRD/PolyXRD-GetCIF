class LicenseDialog(QDialog):
    """版权 / 许可对话框（精简中英对照）。"""

    def __init__(self, parent: Optional[QDialog] = None, version: str | None = None) -> None:
        super().__init__(parent)
        self.setWindowTitle(f"版权与许可 - {__app_name__}")
        self.setMinimumWidth(480)

        root = QVBoxLayout(self)

        body = QTextBrowser()
        body.setOpenExternalLinks(True)
        body.setFrameShape(QTextBrowser.Shape.NoFrame)
        body.setHtml(LICENSE_HTML.replace("{version}", version or __version__))
        root.addWidget(body)

        ok = QPushButton("确定")
        ok.setObjectName("primary")
        ok.clicked.connect(self.accept)
        root.addWidget(ok, alignment=Qt.AlignmentFlag.AlignCenter)


def show_license(parent=None, version: str | None = None) -> None:
    """便捷入口：模态显示版权 / 许可对话框。"""
    LicenseDialog(parent, version).exec()


